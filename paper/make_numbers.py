"""
Generate paper/numbers_biorxiv.tex -- LaTeX macros for every number in the bioRxiv manuscript
that comes from a results file, so tables and prose update mechanically when results change.

Sources (all optional; a missing file falls back to the values recorded in RESEARCH_NOTES.md and
is flagged on stderr so a stale fallback can never slip into a compiled PDF unnoticed):
  --haxby-final   haxby_vt_final_results.json      (haxby_vt_final.py)
  --nilearn       haxby_nilearn_baseline_results.json (haxby_nilearn_baseline.py)
  --starplus      starplus_nested_cv_results.json  (starplus_glm_nested_cv.py)
  --starplus-perm starplus_permutation_results.json (starplus_permutation_test.py)
  --combined      haxby_combined_levers_results.json (haxby_combined_levers_nested_cv.py)
"""
import argparse
import json
import os
import sys
from collections import Counter

import numpy as np

FALLBACK_FLAGS = []


def load(path, label):
    if path and os.path.isfile(path):
        with open(path) as f:
            return json.load(f)
    FALLBACK_FLAGS.append(label)
    return None


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}\\%"


def f3(x):
    return f"{x:.3f}"


def macro(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--haxby-final")
    ap.add_argument("--nilearn")
    ap.add_argument("--starplus")
    ap.add_argument("--starplus-perm")
    ap.add_argument("--combined")
    ap.add_argument("--haxby-local", help="haxby_vt_final results from a second library-version set (robustness check)")
    ap.add_argument("--nilearn-local", help="nilearn-baseline results from a second library-version set (robustness check)")
    ap.add_argument("--ladder", help="haxby_ladder_results.json (tutorial pipeline on VT -> +standardisation -> +logistic)")
    ap.add_argument("--starplus-ablation", help="starplus_ablation_results.json (beta-series with vs without selection)")
    ap.add_argument("--extras", help="directory with robustness results: haxby_null_leakage_{a,b}.json, "
                                     "starplus_null_leakage.json, leakage_simulation.json, "
                                     "selection_stats_m{3,5}.json, wb_ablation_{a,b}.json")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "numbers_biorxiv.tex"))
    a = ap.parse_args()

    out = ["% AUTO-GENERATED by make_numbers.py -- do not edit by hand"]

    # ------------------------------------------------------------------ StarPlus
    sp = load(a.starplus, "starplus nested CV")
    spp = load(a.starplus_perm, "starplus permutation")
    sp_fallback = {"04799": ([1.0, 1.0, 1.0, 0.75, 0.875, 1.0, 1.0, 0.875, 0.875, 0.875]),
                   "04820": ([0.875, 0.875, 0.875, 0.875, 1.0, 0.625, 1.0, 0.875, 0.75, 0.875]),
                   "04847": ([1.0] * 10)}
    sp_base = {"04799": 0.762, "04820": 0.787, "04847": 1.000}
    rows, means = [], []
    null_ranges = []
    for subj in ["04799", "04820", "04847"]:
        folds = np.array(sp[subj]["per_fold_scores"]) if sp else np.array(sp_fallback[subj])
        m, sd = folds.mean(), folds.std(ddof=1)
        if spp:
            p = spp[subj]["p_value"]
            nm = float(np.mean(spp[subj]["null_means"]))
            n_perm = len(spp[subj]["null_means"])
        else:
            p, nm, n_perm = 1 / 51, {"04799": 0.477, "04820": 0.464, "04847": 0.502}[subj], 50
        null_ranges.append(nm)
        means.append(m)
        rows.append(f"{subj} & {f3(m)} $\\pm$ {f3(sd)} & {f3(sp_base[subj])} & {f3(nm)} & {p:.4f} \\\\")
    out += [macro("spRows", " ".join(rows)),
            macro("spMean", f3(np.mean(means))), macro("spMeanPct", pct(np.mean(means))),
            macro("spBaseMean", f3(np.mean(list(sp_base.values())))),
            macro("spBaseMeanPct", pct(np.mean(list(sp_base.values())))),
            macro("spPermN", str(n_perm)), macro("spPfloor", f"{1 / (n_perm + 1):.4f}"),
            macro("spNullRange", f"{min(null_ranges):.2f}--{max(null_ranges):.2f}")]

    # ------------------------------------------------------------------ nilearn baseline
    nl = load(a.nilearn, "nilearn baseline")
    if nl:
        ovr_pub, ovr_grp = nl["OvR"]["cv5_ungrouped_mean"], nl["OvR"]["logo_grouped_mean"]
        ovo_pub, ovo_grp = nl["OvO"]["cv5_ungrouped_mean"], nl["OvO"]["logo_grouped_mean"]
        nl_versions = nl["versions"]
    else:
        ovr_pub, ovr_grp, ovo_pub, ovo_grp = 0.535, 0.414, 0.472, 0.313
        nl_versions = {}
    out += [macro("nlOvRPub", f3(ovr_pub)), macro("nlOvRGrouped", f3(ovr_grp)),
            macro("nlOvOPub", f3(ovo_pub)), macro("nlOvOGrouped", f3(ovo_grp)),
            macro("nlOvRPubPct", pct(ovr_pub)), macro("nlOvRGroupedPct", pct(ovr_grp)),
            macro("nlOvRDeltaPts", f"{100 * (ovr_pub - ovr_grp):.1f}"),
            macro("nlOvODeltaPts", f"{100 * (ovo_pub - ovo_grp):.1f}")]

    # ------------------------------------------------------------------ Haxby final
    hx = load(a.haxby_final, "haxby final (VT baseline + permutation)")
    if hx:
        versions = hx["versions"]
        cfg = hx["config"]
        subs = hx["subjects"]
        n_perm = cfg["n_permutations"]
        inner = cfg["inner_splits"]
        rows, ours, base, ps, null_means, null_max, sds = [], [], [], [], [], [], []
        k_all, k_total, k_counter = 0, 0, Counter()
        for s in sorted(subs, key=int):
            r = subs[s]
            o, b = r["active_voxel"], r["all_vt_baseline"]
            ours.append(o["mean"]); base.append(b["mean"]); ps.append(r["permutation"]["p_value"])
            null_means.append(r["permutation"]["null_mean"]); null_max.append(r["permutation"]["null_max"])
            sds.append(o["sd"])
            # a chosen k >= the subject's VT voxel count is identical to "all" (no selection)
            n_vt = r["n_vt_voxels"]
            for c in o["per_fold_choices"]:
                k = c["k"]
                effective = "all" if (k == "all" or int(k) >= n_vt) else str(k)
                k_counter[effective] += 1
                k_total += 1
                if effective == "all":
                    k_all += 1
            rows.append(f"{s} & {r['n_vt_voxels']} & {f3(b['mean'])} $\\pm$ {f3(b['sd'])} & "
                        f"{f3(o['mean'])} $\\pm$ {f3(o['sd'])} & ${100 * (o['mean'] - b['mean']):+.1f}$ & "
                        f"{f3(r['permutation']['null_mean'])} & {r['permutation']['p_value']:.4f} \\\\")
        wins = sum(1 for o, b in zip(ours, base) if o > b)
        deltas = [100 * (o - b) for o, b in zip(ours, base)]
        subj2 = subs.get("2")
        # most common non-'all' k
        k_nonall = Counter({k: v for k, v in k_counter.items() if k != "all"})
        k_mode = k_nonall.most_common(1)[0][0] if k_nonall else "--"
        out += [macro("hxRows", " ".join(rows)),
                macro("hxMeanOurs", f3(np.mean(ours))), macro("hxMeanOursPct", pct(np.mean(ours))),
                macro("hxMeanBase", f3(np.mean(base))), macro("hxMeanBasePct", pct(np.mean(base))),
                macro("hxMeanDeltaPts", f"${100 * (np.mean(ours) - np.mean(base)):+.1f}$"),
                macro("hxWins", str(wins)),
                macro("hxDeltaRange", f"${min(deltas):+.1f}$ to ${max(deltas):+.1f}$"),
                macro("hxMaxAbsDelta", f"{max(abs(d) for d in deltas):.1f}"),
                macro("hxMinOurs", f3(min(ours))), macro("hxMaxOurs", f3(max(ours))),
                macro("hxPermN", str(n_perm)), macro("hxPfloor", f"{1 / (n_perm + 1):.4f}"),
                macro("hxPmax", f"{max(ps):.4f}"),
                macro("hxNullRange", f"{min(null_means):.3f}--{max(null_means):.3f}"),
                macro("hxNullMaxOverall", f3(max(null_max))),
                macro("hxSDRange", f"{min(sds):.2f}--{max(sds):.2f}"),
                macro("hxInnerSplits", str(inner)),
                macro("hxKallCount", str(k_all)), macro("hxKfoldsTotal", str(k_total)),
                macro("hxKsubsetCount", str(k_total - k_all)), macro("hxKmode", str(k_mode)),
                macro("hxOursSubjTwo", f3(subj2["active_voxel"]["mean"]) if subj2 else "--"),
                macro("hxBaseSubjTwo", f3(subj2["all_vt_baseline"]["mean"]) if subj2 else "--"),
                macro("hxOursSubjTwoPct", pct(subj2["active_voxel"]["mean"]) if subj2 else "--"),
                macro("hxNsubjects", str(len(subs)))]
    else:
        versions = {}
        out += [macro("hxRows", "\\multicolumn{7}{c}{\\textbf{[PENDING: haxby\\_vt\\_final\\_results.json]}} \\\\"),
                macro("hxMeanOurs", "0.717"), macro("hxMeanOursPct", "71.7\\%"),
                macro("hxMeanBase", "?"), macro("hxMeanBasePct", "?\\%"), macro("hxMeanDeltaPts", "?"),
                macro("hxWins", "?"), macro("hxDeltaRange", "?"), macro("hxMaxAbsDelta", "?"),
                macro("hxMinOurs", "0.576"), macro("hxMaxOurs", "0.782"),
                macro("hxPermN", "?"), macro("hxPfloor", "?"), macro("hxPmax", "?"),
                macro("hxNullRange", "?"), macro("hxNullMaxOverall", "?"), macro("hxSDRange", "?"),
                macro("hxInnerSplits", "4"), macro("hxKallCount", "?"), macro("hxKfoldsTotal", "?"),
                macro("hxKsubsetCount", "?"), macro("hxKmode", "?"),
                macro("hxOursSubjTwo", "0.704"), macro("hxBaseSubjTwo", "?"), macro("hxOursSubjTwoPct", "70.4\\%"),
                macro("hxNsubjects", "6")]

    # ------------------------------------------------------------------ preprocessing table rows
    beta_wb = {"1": 0.510, "2": 0.375, "3": 0.750, "4": 0.646, "5": 0.830, "6": 0.698}
    beta_vt = {"1": 0.562, "2": 0.573, "3": 0.719, "4": 0.646, "5": 0.818, "6": 0.688}
    raw_wb = {"1": 0.745, "2": 0.619, "3": 0.735, "4": 0.593, "5": 0.591, "6": 0.784}
    raw_vt_fallback = {"1": 0.767, "2": 0.704, "3": 0.698, "4": 0.576, "5": 0.777, "6": 0.782}
    prows = []
    for s in ["1", "2", "3", "4", "5", "6"]:
        if hx and s in hx["subjects"]:
            rv = f3(hx["subjects"][s]["active_voxel"]["mean"])
        else:
            rv = f"{f3(raw_vt_fallback[s])}$^{{\\dagger}}$"
        prows.append(f"{s} & {f3(beta_wb[s])} & {f3(beta_vt[s])} & {f3(raw_wb[s])} & {rv} \\\\")
    out.append(macro("hxPreprocRows", " ".join(prows)))

    # ------------------------------------------------------------------ combined levers (k / clf choices)
    cb = load(a.combined, "combined levers")
    if cb:
        restricted = Counter(); clfs = Counter(); total = 0
        for s, r in cb.items():
            for c in r["per_fold_choices"]:
                restricted[c["restricted"]] += 1; clfs[c["clf"]] += 1; total += 1
        out += [macro("cbRestrictedCount", str(restricted[True])), macro("cbFoldsTotal", str(total)),
                macro("cbLDACount", str(clfs.get("LinearDiscriminantAnalysis", 0))),
                macro("cbMean", f3(np.mean([r["mean"] for r in cb.values()])))]
    else:
        out += [macro("cbRestrictedCount", "?"), macro("cbFoldsTotal", "?"), macro("cbLDACount", "?"), macro("cbMean", "0.720")]

    # ------------------------------------------------------------------ StarPlus ablation
    sab = load(a.starplus_ablation, "starplus ablation (selection vs no-selection)")
    if sab:
        ss = sab["subjects"]
        rows, sel_m, nos_m, perm_ps, null_ms = [], [], [], [], []
        k_all = k_total = 0
        for sid in sorted(ss):
            r = ss[sid]
            sel, nos = r["selection"], r["no_selection"]
            sel_m.append(sel["mean"]); nos_m.append(nos["mean"])
            kh = sel.get("k_histogram", {})
            n_vox = r["n_voxels"]
            folds_all = sum(v for k, v in kh.items() if k == "all" or (k.isdigit() and int(k) >= n_vox))
            k_all += folds_all; k_total += sum(kh.values())
            perm = nos.get("permutation")
            if perm:
                perm_ps.append(perm["p_value"]); null_ms.append(perm["null_mean"])
            pcol = f"{perm['p_value']:.4f}" if perm else "--"
            rows.append(f"{sid} & {r['n_voxels']} & {f3(nos['mean'])} $\\pm$ {f3(nos['sd'])} & "
                        f"{f3(sel['mean'])} $\\pm$ {f3(sel['sd'])} & ${100 * (sel['mean'] - nos['mean']):+.1f}$ & {pcol} \\\\")
        out += [macro("spAblRows", " ".join(rows)),
                macro("spAblNoSelMean", f3(np.mean(nos_m))), macro("spAblSelMean", f3(np.mean(sel_m))),
                macro("spAblNoSelMeanPct", pct(np.mean(nos_m))), macro("spAblSelMeanPct", pct(np.mean(sel_m))),
                macro("spAblDeltaPts", f"${100 * (np.mean(sel_m) - np.mean(nos_m)):+.1f}$"),
                macro("spAblKallCount", str(k_all)), macro("spAblKfoldsTotal", str(k_total)),
                macro("spAblKsubsetCount", str(k_total - k_all)),
                macro("spAblPermN", str(ss[sorted(ss)[0]]["no_selection"].get("permutation", {}).get("n", "?"))),
                macro("spAblPmax", f"{max(perm_ps):.4f}" if perm_ps else "?"),
                macro("spAblNullRange", f"{min(null_ms):.2f}--{max(null_ms):.2f}" if null_ms else "?")]
    else:
        out += [macro("spAblRows", "\\multicolumn{6}{c}{[PENDING: starplus ablation]} \\\\"),
                macro("spAblNoSelMean", "?"), macro("spAblSelMean", "?"),
                macro("spAblNoSelMeanPct", "?"), macro("spAblSelMeanPct", "?"), macro("spAblDeltaPts", "?"),
                macro("spAblKallCount", "?"), macro("spAblKfoldsTotal", "?"), macro("spAblKsubsetCount", "?"),
                macro("spAblPermN", "?"), macro("spAblPmax", "?"), macro("spAblNullRange", "?")]

    # ------------------------------------------------------------------ decomposition ladder
    ld = load(a.ladder, "haxby ladder")
    steps = [("A_tutorial_pipeline_VT", "ldA"), ("B_plus_standardisation", "ldB"), ("C_plus_logistic_regression", "ldC")]
    if ld:
        ls = ld["subjects"]
        for key, name in steps:
            s2 = ls.get("2")
            out += [macro(name + "SubjTwo", f3(s2[key]["mean"]) if s2 else "?"),
                    macro(name + "SubjTwoSD", f3(s2[key]["sd"]) if s2 else "?"),
                    macro(name + "Mean", f3(np.mean([ls[s][key]["mean"] for s in ls])))]
        out += [macro("ldNsubjects", str(len(ls)))]
        # subject-2 step deltas (points): VT restriction, standardisation, logistic regression, tuned C
        s2 = ls.get("2")
        if s2 and hx and "2" in hx["subjects"]:
            a_, b_, c_ = (s2[k]["mean"] for k, _ in steps)
            d_ = hx["subjects"]["2"]["all_vt_baseline"]["mean"]
            for name, val in (("ldDeltaVT", a_ - ovr_grp), ("ldDeltaScale", b_ - a_),
                              ("ldDeltaLogit", c_ - b_), ("ldDeltaTune", d_ - c_)):
                out += [macro(name, f"${100 * val:+.1f}$")]
        else:
            out += [macro(n, "?") for n in ("ldDeltaVT", "ldDeltaScale", "ldDeltaLogit", "ldDeltaTune")]
        # per-subject rows for a compact ladder table: subject, A, B, C, D(no selection), E(+selection)
        rows = []
        for s in sorted(ls, key=int):
            d = hx["subjects"][s]["all_vt_baseline"]["mean"] if hx and s in hx["subjects"] else None
            e = hx["subjects"][s]["active_voxel"]["mean"] if hx and s in hx["subjects"] else None
            rows.append(f"{s} & {f3(ls[s]['A_tutorial_pipeline_VT']['mean'])} & {f3(ls[s]['B_plus_standardisation']['mean'])} & "
                        f"{f3(ls[s]['C_plus_logistic_regression']['mean'])} & {f3(d) if d is not None else '--'} & "
                        f"{f3(e) if e is not None else '--'} \\\\")
        out += [macro("ldRows", " ".join(rows))]
    else:
        for _, name in steps:
            out += [macro(name + "SubjTwo", "?"), macro(name + "SubjTwoSD", "?"), macro(name + "Mean", "?")]
        out += [macro("ldNsubjects", "?"), macro("ldRows", "\\multicolumn{6}{c}{[PENDING: ladder]} \\\\")]
        out += [macro(n, "?") for n in ("ldDeltaVT", "ldDeltaScale", "ldDeltaLogit", "ldDeltaTune")]

    # ------------------------------------------------------------------ robustness extras
    def xload(name):
        return load(os.path.join(a.extras, name) if a.extras else None, f"extras: {name}")

    # Haxby protocols under block-permuted labels
    na, nb = xload("haxby_null_leakage_a.json"), xload("haxby_null_leakage_b.json")
    keys = ["A_tutorial_cv5_ungrouped", "B_tutorial_loro", "C_leaky_sweep_wholebrain", "C_leaky_sweep_vt"]
    names = ["NullTutUng", "NullTutLoro", "NullLeakWB", "NullLeakVT"]
    if na and nb:
        hs = {**na["subjects"], **nb["subjects"]}
        rows = []
        for s in sorted(hs, key=int):
            r = hs[s]
            rows.append(f"{s} & " + " & ".join(f"{f3(r['real'][k])} / {f3(np.mean(r['null'][k]))}" for k in keys) + " \\\\")
        out += [macro("nullRows", " ".join(rows)), macro("nullNperm", str(na["n_permutations"]))]
        for k, n in zip(keys, names):
            out += [macro(f"x{n}", f3(np.mean([np.mean(hs[s]["null"][k]) for s in hs]))),
                    macro(f"x{n}Real", f3(np.mean([hs[s]["real"][k] for s in hs])))]
        ung = np.mean([np.mean(hs[s]["null"][keys[0]]) for s in hs])
        out += [macro("xNullTutUngPct", pct(ung))]
        out += [macro("xNullTutUngInflPts", f"{100 * (ung - 0.125):.1f}"),
                macro("xNullVersions", f"\\texttt{{scikit-learn}} {na['versions']['scikit-learn']} / "
                                       f"\\texttt{{nilearn}} {na['versions']['nilearn']}")]
    else:
        out += [macro("nullRows", "\\multicolumn{5}{c}{[PENDING: null leakage]} \\\\"), macro("nullNperm", "?"),
                macro("xNullTutUngInflPts", "?"), macro("xNullVersions", "?"), macro("xNullTutUngPct", "?")]
        out += [macro(f"x{n}", "?") for n in names] + [macro(f"x{n}Real", "?") for n in names]

    # StarPlus pre-fix flat sweep under permuted labels
    spn = xload("starplus_null_leakage.json")
    if spn:
        ss = spn["subjects"]
        nm = [ss[s]["null_mean"] for s in ss]
        out += [macro("spNullLeakRange", f"{min(nm):.3f}--{max(nm):.3f}"),
                macro("spNullLeakMean", f3(np.mean(nm))), macro("spNullLeakMeanPct", pct(np.mean(nm))),
                macro("spNullLeakRangePct", f"{100 * min(nm):.1f}--{pct(max(nm))}"),
                macro("spNullLeakMax", f3(max(ss[s]["null_max"] for s in ss))),
                macro("spNullLeakN", str(spn["n_null"]))]
    else:
        out += [macro(n, "?") for n in ("spNullLeakRange", "spNullLeakMean", "spNullLeakMeanPct", "spNullLeakRangePct",
                                        "spNullLeakMax", "spNullLeakN")]

    # ground-truth simulation
    sim = xload("leakage_simulation.json")
    if sim:
        fr, bt = sim["frames"], sim["betas"]
        def m(rows, key, **cond):
            sel = [r[key] for r in rows if all(r[c] == v for c, v in cond.items())]
            return float(np.mean(sel))
        corr_all = [m(fr, "correct", p=p, phi=phi) for p in sim["config"]["p_values"] for phi in sim["config"]["phi_values"]]
        corr_all += [m(bt, "correct", p=p) for p in sim["config"]["p_values"]]
        out += [macro("simSeeds", str(sim["config"]["n_seeds"])),
                macro("simCorrectRange", f"{min(corr_all):.2f}--{max(corr_all):.2f}"),
                macro("simSelBeforeTwoK", f3(m(fr, "select_before", p=2000, phi=0.0))),
                macro("simSelBeforeFortyK", f3(m(fr, "select_before", p=40000, phi=0.0))),
                macro("simSelBeforeFortyKAR", f3(m(fr, "select_before", p=40000, phi=0.5))),
                macro("simBetaSelTenK", f3(m(bt, "select_before", p=10000))),
                macro("simUngPhiZero", f3(np.mean([m(fr, "ungrouped_cv5", p=p, phi=0.0) for p in sim["config"]["p_values"]]))),
                macro("simUngPhiEight", f3(np.mean([m(fr, "ungrouped_cv5", p=p, phi=0.8) for p in sim["config"]["p_values"]])))]
    else:
        out += [macro(n, "?") for n in ("simSeeds", "simCorrectRange", "simSelBeforeTwoK", "simSelBeforeFortyK",
                                        "simSelBeforeFortyKAR", "simBetaSelTenK", "simUngPhiZero", "simUngPhiEight")]

    # selection-vs-no-selection equivalence statistics
    e3, e5 = xload("selection_stats_m3.json"), xload("selection_stats_m5.json")
    if e3 and e5:
        ps = [r["p"] for r in e3["per_subject"]]
        out += [macro("eqN", str(e3["n_subjects"])), macro("eqMeanDelta", f"${100 * e3['mean_delta']:+.1f}$"),
                macro("eqCI", f"${100 * e3['ci90'][0]:+.1f}$ to ${100 * e3['ci90'][1]:+.1f}$"),
                macro("eqPthree", f"{e3['p_tost']:.3f}"), macro("eqPfive", f"{e5['p_tost']:.3f}"),
                macro("eqMinP", f"{min(ps):.2f}"), macro("eqNsig", str(e3["n_significant_uncorrected"]))]
    else:
        out += [macro(n, "?") for n in ("eqN", "eqMeanDelta", "eqCI", "eqPthree", "eqPfive", "eqMinP", "eqNsig")]

    # whole-brain ablation (selection vs no selection on all ~40k voxels)
    wa, wb = xload("wb_ablation_a.json"), xload("wb_ablation_b.json")
    if wa and wb:
        ws = {**wa["subjects"], **wb["subjects"]}
        rows, sel_m, nos_m = [], [], []
        k_all = k_tot = 0
        for s in sorted(ws, key=int):
            r = ws[s]
            sel, nos = r["selection"], r["no_selection"]
            sel_m.append(sel["mean"]); nos_m.append(nos["mean"])
            kh = sel.get("k_histogram", {})
            k_all += kh.get("all", 0); k_tot += sum(kh.values())
            rows.append(f"{s} & {f3(nos['mean'])} $\\pm$ {f3(nos['sd'])} & {f3(sel['mean'])} $\\pm$ {f3(sel['sd'])} & "
                        f"${100 * (sel['mean'] - nos['mean']):+.1f}$ \\\\")
        out += [macro("wbRows", " ".join(rows)), macro("wbNoSelMean", f3(np.mean(nos_m))),
                macro("wbNoSelMeanPct", pct(np.mean(nos_m))), macro("wbSelMeanPct", pct(np.mean(sel_m))),
                macro("wbSelMean", f3(np.mean(sel_m))),
                macro("wbDeltaPts", f"${100 * (np.mean(sel_m) - np.mean(nos_m)):+.1f}$"),
                macro("wbWins", str(sum(1 for x, y in zip(sel_m, nos_m) if x > y))),
                macro("wbKall", str(k_all)), macro("wbKtot", str(k_tot)),
                macro("wbMinDelta", f"{100 * min(x - y for x, y in zip(sel_m, nos_m)):.1f}"),
                macro("wbMaxDelta", f"{100 * max(x - y for x, y in zip(sel_m, nos_m)):.1f}")]
        wst = xload("wb_selection_stats.json")
        out += [macro("wbMaxP", f"{wst['max_p']:.3f}" if wst else "?")]
        sa, sb = xload("wb_strongc_a.json"), xload("wb_strongc_b.json")
        if sa and sb:
            sc = {**sa["subjects"], **sb["subjects"]}
            cs = [c["C"] for s in sc for c in sc[s]["no_selection"]["per_fold_choices"]]
            maxdiff = max(abs(sc[s]["no_selection"]["mean"] - ws[s]["no_selection"]["mean"]) for s in sc)
            out += [macro("wbStrongMinC", f"10^{{{int(np.log10(min(sa['config']['c_values'])))}}}"),
                    macro("wbStrongMinChosen", f"{min(cs):g}"), macro("wbStrongMaxDiff", f"{100 * maxdiff:.1f}")]
        else:
            out += [macro(n, "?") for n in ("wbStrongMinC", "wbStrongMinChosen", "wbStrongMaxDiff")]
    else:
        out += [macro("wbRows", "\\multicolumn{4}{c}{[PENDING: whole-brain ablation]} \\\\")]
        out += [macro(n, "?") for n in ("wbNoSelMean", "wbSelMean", "wbDeltaPts", "wbWins", "wbKall", "wbKtot",
                                        "wbMinDelta", "wbMaxDelta", "wbMaxP", "wbNoSelMeanPct", "wbSelMeanPct", "wbStrongMinC", "wbStrongMinChosen",
                                        "wbStrongMaxDiff")]

    # ------------------------------------------------------------------ software versions
    v = versions or nl_versions
    out += [macro("skVersion", v.get("scikit-learn", "?")), macro("nilearnVersion", v.get("nilearn", "?")),
            macro("pyVersion", v.get("python", "?")), macro("numpyVersion", v.get("numpy", "?")),
            macro("nlSkVersion", nl_versions.get("scikit-learn", v.get("scikit-learn", "?"))),
            macro("nlNilearnVersion", nl_versions.get("nilearn", v.get("nilearn", "?")))]

    # ------------------------------------------------------------------ cross-version robustness check
    # the same haxby_vt_final.py re-run under a second library-version set (local venv vs Kaggle)
    hl = load(a.haxby_local, "haxby local cross-version run")
    if hx and hl:
        common = sorted(set(hx["subjects"]) & set(hl["subjects"]), key=int)
        diffs = [100 * abs(hx["subjects"][s]["active_voxel"]["mean"] - hl["subjects"][s]["active_voxel"]["mean"])
                 for s in common]
        bdiffs = [100 * abs(hx["subjects"][s]["all_vt_baseline"]["mean"] - hl["subjects"][s]["all_vt_baseline"]["mean"])
                  for s in common]
        lv = hl["versions"]
        out += [macro("hxAltSkVersion", lv.get("scikit-learn", "?")), macro("hxAltNilearnVersion", lv.get("nilearn", "?")),
                macro("hxAltNsubjects", str(len(common))),
                macro("hxAltMaxDiff", f"{max(diffs + bdiffs):.1f}" if common else "?")]
    else:
        out += [macro("hxAltSkVersion", "?"), macro("hxAltNilearnVersion", "?"), macro("hxAltNsubjects", "?"),
                macro("hxAltMaxDiff", "?")]
    nll = load(a.nilearn_local, "nilearn baseline cross-version run")
    if nl and nll:
        d = [100 * abs(nl[k][m] - nll[k][m]) for k in ("OvR", "OvO") for m in ("cv5_ungrouped_mean", "logo_grouped_mean")]
        out += [macro("nlAltMaxDiff", f"{max(d):.1f}")]
    else:
        out += [macro("nlAltMaxDiff", "?")]

    with open(a.out, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {a.out} ({len(out)} lines)")
    if FALLBACK_FLAGS:
        print("WARNING: fallback values used for:", ", ".join(FALLBACK_FLAGS), file=sys.stderr)


if __name__ == "__main__":
    main()
